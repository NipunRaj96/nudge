#!/usr/bin/env python3
"""Regenerate the Material Symbols subset + Kotlin name->glyph map.

Run after adding a new icon name anywhere in app/src/main/java (Symbol("new_icon"), NavItem("new_icon", ...)).
  python3 -m venv /tmp/v && /tmp/v/bin/pip install fonttools && /tmp/v/bin/python tools/subset_symbols.py
Downloads the full variable font (~10 MB) once into tools/.cache (gitignored).
"""
import glob, os, re, urllib.request
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer
from fontTools import subset

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
CACHE = os.path.join(os.path.dirname(__file__), ".cache"); os.makedirs(CACHE, exist_ok=True)
FULL = os.path.join(CACHE, "MaterialSymbolsOutlined.ttf")
URL = "https://github.com/google/material-design-icons/raw/master/variablefont/MaterialSymbolsOutlined%5BFILL%2CGRAD%2Copsz%2Cwght%5D.ttf"
if not os.path.exists(FULL): urllib.request.urlretrieve(URL, FULL)

font = TTFont(FULL)
cmap = font.getBestCmap(); rev = {v: k for k, v in cmap.items()}; glyph_cp = {g: c for c, g in cmap.items()}
names = {}
for lookup in font["GSUB"].table.LookupList.Lookup:
    for st in lookup.SubTable:
        st = getattr(st, "ExtSubTable", st)
        for first, ligs in getattr(st, "ligatures", {}).items():
            for lig in ligs:
                try: names["".join(chr(rev[g]) for g in [first] + lig.Component)] = lig.LigGlyph
                except KeyError: pass

src = "".join(open(p).read() for p in glob.glob(os.path.join(ROOT, "app/src/main/java/**/*.kt"), recursive=True) if not p.endswith("SymbolGlyphs.kt"))
used = sorted(q for q in set(re.findall(r'"([a-z][a-z0-9_]*)"', src)) if q in names)
missing = [s for s in set(re.findall(r'Symbol\(\s*"([a-z0-9_]+)"', src)) if s not in names]
assert not missing, f"unknown icon names: {missing}"
mapping = {n: glyph_cp[names[n]] for n in used}

with open(os.path.join(ROOT, "app/src/main/java/com/nudge/app/ui/components/SymbolGlyphs.kt"), "w") as o:
    o.write("package com.nudge.app.ui.components\n\n// GENERATED by tools/subset_symbols.py - do not edit.\ninternal val SymbolGlyphs: Map<String, String> = mapOf(\n")
    for n, c in mapping.items(): o.write(f'  "{n}" to "\\u{c:04X}",\n')
    o.write(")\n")

pinned = os.path.join(CACHE, "pinned.ttf")
instancer.instantiateVariableFont(TTFont(FULL), {"wght": 400, "GRAD": 0, "opsz": 24}).save(pinned)
opts = subset.Options(); opts.layout_features = []; opts.hinting = False; opts.notdef_outline = True; opts.name_IDs = [1, 2]
f = subset.load_font(pinned, opts); s = subset.Subsetter(opts); s.populate(unicodes=list(mapping.values())); s.subset(f)
out = os.path.join(ROOT, "app/src/main/res/font/material_symbols_subset.ttf")
subset.save_font(f, out, opts)
print(f"{len(mapping)} icons, {os.path.getsize(out)} bytes")
